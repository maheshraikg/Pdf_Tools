"""Builds lib/l10n/translations.dart from tool/l10n/keys.txt and one
`<language code>.txt` file per language (lines `number|translation`).

Lines may be left out: the English text is shown for them. A translation
whose {0}, {1}, ... placeholders differ from the English is rejected.

Run: python3 tool/l10n/build.py
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
DIR = ROOT / 'tool/l10n'
LANGS = ['hi', 'kn', 'ml', 'ta', 'te', 'mr', 'bn', 'gu']


def decode(k):
    return re.sub(r'\\+n', '\n', k)


def dart(s):
    return "'" + (s.replace('\\', '\\\\').replace("'", "\\'")
                  .replace('$', '\\$').replace('\n', '\\n')) + "'"


def holes(s):
    return sorted(set(re.findall(r'\{\d+\}', s)))


keys = {}
for line in (DIR / 'keys.txt').read_text().splitlines():
    n, _, k = line.partition('|')
    keys[int(n)] = decode(k)

out = ['// Generated by tool/l10n/build.py from tool/l10n/*.txt. Do not edit.',
       '// ignore_for_file: lines_longer_than_80_chars', '',
       'const Map<String, Map<String, String>> translations = {', "  'en': {},"]
problems = 0
for lang in LANGS:
    f = DIR / f'{lang}.txt'
    if not f.exists():
        continue
    out.append(f"  '{lang}': {{")
    count = 0
    for no, line in enumerate(f.read_text().splitlines(), 1):
        if not line.strip() or line.startswith('#'):
            continue
        n, sep, text = line.partition('|')
        if not sep or not n.strip().isdigit() or int(n) not in keys:
            print(f'{lang}.txt:{no}: bad line: {line[:60]}')
            problems += 1
            continue
        en, text = keys[int(n)], decode(text.strip())
        if en.endswith('\n') and not text.endswith('\n'):
            text += '\n'
        if holes(en) != holes(text):
            print(f'{lang}.txt:{no}: placeholders differ: {en!r} -> {text!r}')
            problems += 1
            continue
        out.append(f'    {dart(en)}: {dart(text)},')
        count += 1
    out.append('  },')
    print(f'{lang}: {count} of {len(keys)} strings')
out.append('};')
(ROOT / 'lib/l10n/translations.dart').write_text('\n'.join(out) + '\n')
sys.exit(1 if problems else 0)
