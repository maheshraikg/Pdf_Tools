"""Generates lib/l10n/*.dart from the translation lists in this folder.

    python3 tool/l10n/gen.py

Each tr_*.py list follows, in order, the English strings in
lib/app/strings.dart (_t/_f first arguments). After adding a string there,
add its translation at the same position in every list; the script checks
lengths and {0}/%s placeholders.
"""
import json,re,sys,importlib.util,os,subprocess,tempfile
D=os.path.dirname(os.path.abspath(__file__))
ROOT=os.path.dirname(os.path.dirname(D))
tmp=tempfile.mktemp(suffix='.json')
subprocess.run([sys.executable,os.path.join(D,'keys.py'),os.path.join(ROOT,'lib/app/strings.dart'),tmp],check=True,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
keys=json.load(open(tmp)); out=os.path.join(ROOT,'lib/l10n')
T={}
for f in ['tr_ar_ur','tr_hi_ta_kn','tr_bn_id_ms','tr_tr_fr']:
    spec=importlib.util.spec_from_file_location(f,os.path.join(D,f+'.py')); m=importlib.util.module_from_spec(spec); spec.loader.exec_module(m); T.update(m.T)
# Later additions, appended in key order.
for f in ['tr_more','tr_more2','tr_more3','tr_more4','tr_more5','tr_more6','tr_more7','tr_more8','tr_more9','tr_more10','tr_more11','tr_more12','tr_more13']:
    spec=importlib.util.spec_from_file_location(f,os.path.join(D,f+'.py')); m=importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
    for code,vals in m.T.items(): T[code]=T[code]+vals
HIJRI={
'ar':['محرم','صفر','ربيع الأول','ربيع الآخر','جمادى الأولى','جمادى الآخرة','رجب','شعبان','رمضان','شوال','ذو القعدة','ذو الحجة'],
'ur':['محرم','صفر','ربیع الاول','ربیع الثانی','جمادی الاول','جمادی الثانی','رجب','شعبان','رمضان','شوال','ذوالقعدہ','ذوالحجہ'],
'hi':['मुहर्रम','सफ़र','रबी-उल-अव्वल','रबी-उल-आख़िर','जुमादा-अल-ऊला','जुमादा-अल-आख़िरा','रजब','शाबान','रमज़ान','शव्वाल','ज़ुल-क़ादा','ज़ुल-हिज्जा'],
'ta':['முஹர்ரம்','ஸஃபர்','ரபீஉல் அவ்வல்','ரபீஉல் ஆகிர்','ஜுமாதல் ஊலா','ஜுமாதல் ஆகிரா','ரஜப்','ஷஃபான்','ரமலான்','ஷவ்வால்','துல் கஃதா','துல் ஹஜ்'],
'kn':['ಮುಹರ್ರಂ','ಸಫರ್','ರಬೀಉಲ್ ಅವ್ವಲ್','ರಬೀಉಲ್ ಆಖಿರ್','ಜುಮಾದಲ್ ಊಲಾ','ಜುಮಾದಲ್ ಆಖಿರಾ','ರಜಬ್','ಶಅಬಾನ್','ರಮಝಾನ್','ಶವ್ವಾಲ್','ದುಲ್ ಖಅದಾ','ದುಲ್ ಹಿಜ್ಜಾ'],
'bn':['মুহাররম','সফর','রবিউল আউয়াল','রবিউস সানি','জমাদিউল আউয়াল','জমাদিউস সানি','রজব','শাবান','রমজান','শাওয়াল','জিলকদ','জিলহজ'],
'id':['Muharam','Safar','Rabiulawal','Rabiulakhir','Jumadilawal','Jumadilakhir','Rajab','Syakban','Ramadan','Syawal','Zulkaidah','Zulhijah'],
'ms':['Muharam','Safar','Rabiulawal','Rabiulakhir','Jamadilawal','Jamadilakhir','Rejab','Syaaban','Ramadan','Syawal','Zulkaedah','Zulhijah'],
'tr':['Muharrem','Safer','Rebiülevvel','Rebiülahir','Cemaziyelevvel','Cemaziyelahir','Recep','Şaban','Ramazan','Şevval','Zilkade','Zilhicce'],
'fr':['Mouharram','Safar','Rabi al-awwal','Rabi ath-thani','Joumada al-oula','Joumada ath-thania','Rajab','Chaabane','Ramadan','Chawwal',"Dhou al-qi'da",'Dhou al-hijja'],
}
def ph(s): return sorted(re.findall(r'\{\d\}|%s',s))
def q(s): return "'"+s.replace('\\','\\\\').replace("'","\\'").replace('$','\\$')+"'"
bad=0
os.makedirs(out,exist_ok=True)
for code,vals in T.items():
    if len(vals)!=len(keys): print(code,'LEN',len(vals),'!=',len(keys)); bad=1; continue
    for k,v in zip(keys,vals):
        if ph(k)!=ph(v): print(code,'PLACEHOLDER',repr(k),repr(v)); bad=1
    assert len(HIJRI[code])==12
    with open(f'{out}/{code}.dart','w') as f:
        f.write(f'// Generated by tool/l10n; edit the translations there, not here.\n// ignore_for_file: lines_longer_than_80_chars\n\nconst Map<String, String> {code}Strings = {{\n')
        for k,v in zip(keys,vals): f.write(f'  {q(k)}: {q(v)},\n')
        f.write('};\n\nconst List<String> '+code+'HijriMonths = [\n'+''.join(f'  {q(x)},\n' for x in HIJRI[code])+'];\n')
codes=list(T)
with open(f'{out}/tables.dart','w') as f:
    f.write('// Generated by tool/l10n; edit the translations there, not here.\nlibrary;\n\nimport \'../app/settings.dart\';\n')
    for c in codes: f.write(f"import '{c}.dart';\n")
    f.write('\n/// English UI text → translation, per language (not en/ml).\nconst Map<Lang, Map<String, String>> translations = {\n')
    for c in codes: f.write(f'  Lang.{c}: {c}Strings,\n')
    f.write('};\n\n/// Hijri month names per language (not en/ml).\nconst Map<Lang, List<String>> hijriMonthNames = {\n')
    for c in codes: f.write(f'  Lang.{c}: {c}HijriMonths,\n')
    f.write('};\n')
print('languages',codes,'bad' if bad else 'ok')
sys.exit(bad)
