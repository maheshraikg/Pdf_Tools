/// The correction for a place, or an empty map when none is close.
Map<Prayer, int> localCalibration(double lat, double lng) {
  (double, double, List<int>)? best;
  var bestD = double.infinity;
  for (final p in _points) {
    final dy = (p.$1 - lat) * 111.2;
    final dx = (p.$2 - lng) * 111.2 * math.cos(lat * math.pi / 180);
    final d = math.sqrt(dx * dx + dy * dy);
    if (d < bestD) {
      bestD = d;
      best = p;
    }
  }
  if (best == null || bestD > calibrationRadiusKm) return const {};
  const order = [
    Prayer.fajr,
    Prayer.sunrise,
    Prayer.dhuhr,
    Prayer.asr,
    Prayer.maghrib,
    Prayer.isha,
  ];
  return {
    for (var i = 0; i < 6; i++)
      if (best.$3[i] != 0) order[i]: best.$3[i],
  };
}
