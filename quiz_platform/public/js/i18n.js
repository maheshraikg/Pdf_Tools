const dict = { en, kn };
let lang = 'en';
try { lang = localStorage.getItem('lang') || (navigator.language?.startsWith('kn') ? 'kn' : 'en'); } catch { /* storage blocked */ }

export function getLang() { return lang; }
export function setLang(l) {
  lang = dict[l] ? l : 'en';
  try { localStorage.setItem('lang', lang); } catch { /* ignore */ }
  document.documentElement.lang = lang;
}
export function t(key, vars) {
  let s = dict[lang]?.[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
export function fmtDateTime(d) {
  return new Intl.DateTimeFormat(lang === 'kn' ? 'kn-IN' : 'en-IN', { dateStyle: 'medium', timeStyle: 'short' }).format(new Date(d));
}
export function fmtNumber(n) {
  return new Intl.NumberFormat(lang === 'kn' ? 'kn-IN' : 'en-IN').format(n);
}
setLang(lang);
